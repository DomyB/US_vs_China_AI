"use client";

import { COUNTRY_COUNT } from "@/lib/constants";
import Link from "next/link";
import { useRealMeta } from "@/lib/useRealMeta";

/**
 * Data-status strip under the header. Reads the real-data metadata (absent until the first ingestion run) and
 * shows one chip per layer: what is real, what is a model output and how it stands, what is still sample.
 * The full explanation sits behind a "details" toggle so the strip stays one line.
 */
export function SampleBanner() {
  const real = useRealMeta();
  if (real === undefined) return <div role="status" className="h-8 border-b border-rule bg-surface" aria-label="Checking data status" />;
  if (!real) {
    return (
      <div role="status" className="border-b border-rule bg-sample-bg px-4 py-1.5 text-center text-xs font-semibold text-sample">
        SAMPLE DATA · every value on this site is generated by a seeded script for interface development. Nothing shown is a real measurement.
      </div>
    );
  }
  const cov = Object.values(real.coverage);
  const withFacts = cov.filter((c) => c.actions).length;
  const withParliament = cov.filter((c) => c.parliament_available).length;
  const withMedia = cov.filter((c) => c.media_available).length;
  const tm = real.text_model;
  const classified = cov.reduce((n, c) => n + (c.parliament_classified ?? 0) + (c.media_classified ?? 0), 0);
  const statements = cov.reduce((n, c) => n + (c.statements ?? 0), 0);
  const textLabel = classified > 0 && tm?.method ? (tm.validated && tm.kappa_stance_pooled !== null ? `validated κ=${tm.kappa_stance_pooled.toFixed(2)}` : "zero-shot baseline") : "not classified";
  const textShort = classified > 0 && tm?.method ? (tm.validated && tm.kappa_stance_pooled !== null ? `κ=${tm.kappa_stance_pooled.toFixed(2)}` : "zero-shot") : "not classified";
  // The written analysis: generated text exists for every country once the quant step has run; the owner's slot
  // holds briefs that are AI-drafted until the owner reviews them, and the chip says how many are reviewed.
  const interp = real.layers?.interpretation;
  const briefs = real.interpretation_briefs;
  const interpReal = interp === "generated" || interp === "generated+human";
  const interpLabel = !interpReal ? "not in this release" : interp === "generated+human" ? (briefs ? `generated · briefs ${briefs.reviewed}/${briefs.total} reviewed` : "generated") : "generated";
  // `value` is the chip's short text, `long` the full form (the title and the strip's explanation carry it)
  const chips: { label: string; value: string; long?: string; tone: "facts" | "model" | "interp" | "sample" }[] = [
    { label: "Facts", value: `real · ${withFacts}/${COUNTRY_COUNT}`, tone: "facts" },
    // two counts of countries with records, named so the chip never reads as a fraction (legislatures 7 of 12, press 12 of 12)
    { label: "Text", value: `legislatures ${withParliament} · press ${withMedia} · ${textShort}`, long: `legislative records for ${withParliament} countries, press for ${withMedia} · stance ${textLabel}`, tone: classified > 0 ? "model" : "facts" },
    { label: "Indices", value: real.layers?.analysis === "real" ? "computed" : "sample", long: real.layers?.analysis === "real" ? `computed · method ${real.quant_model?.method_version ?? "–"}` : undefined, tone: real.layers?.analysis === "real" ? "model" : "sample" },
    { label: "Forecasts", value: real.layers?.forecast === "real" ? "backtested" : "sample", tone: real.layers?.forecast === "real" ? "model" : "sample" },
    // "Briefs", not "Analysis": the Analysis tab holds the computed index and flags; this chip is about the written briefs
    { label: "Briefs", value: interp === "generated+human" && briefs ? `generated · ${briefs.reviewed}/${briefs.total} reviewed` : interpLabel, long: interpReal ? `written briefs, AI-drafted until the owner reviews them${briefs ? ` · ${briefs.reviewed} of ${briefs.total} reviewed` : ""}` : interpLabel, tone: interpReal ? "interp" : "sample" },
    ...(real.layers?.statements === "real" ? [{ label: "Statements", value: `${statements} coded`, long: `${statements} on a country · dataset coding`, tone: "facts" as const }] : []),
  ];
  const toneCls = { facts: "border-facts/40 text-facts", model: "border-model/40 text-model", interp: "border-interp/40 text-interp", sample: "border-sample/50 text-sample" };
  return (
    <div role="status" className="border-b border-rule bg-surface">
      <details className="mx-auto max-w-[1240px] px-4 sm:px-5">
        <summary className="flex h-8 list-none items-center gap-x-3 text-[11px] text-ink-2 [&::-webkit-details-marker]:hidden">
          <span className="eyebrow shrink-0 whitespace-nowrap"><span className="sm:hidden">Status</span><span className="hidden sm:inline">Data status</span></span>
          <span className="shrink-0 whitespace-nowrap text-ink-3">ingested {real.generated_on}<span className="hidden sm:inline"> · {real.sources_live ? `${real.sources_live.live} of ${real.sources_live.total} sources live` : `${real.sources_ok.length} sources`}</span></span>
          <span className="scroll-x hidden min-w-0 flex-1 gap-1 whitespace-nowrap sm:flex">
            {chips.map((c) => (
              <span key={c.label} className={`chip ${toneCls[c.tone]}`} title={`${c.label}: ${c.long ?? c.value}`}>
                <span className="font-semibold">{c.label}</span>
                {/* the values fit only on a wide screen; the title and the open strip carry them everywhere */}
                <span className="hidden font-normal text-ink-2 2xl:inline">{c.value}</span>
              </span>
            ))}
          </span>
          <span className="ml-auto shrink-0 whitespace-nowrap text-ink-3 underline decoration-dotted">What is real?</span>
        </summary>
        <p className="flex flex-wrap gap-1 pb-1 pt-1 sm:hidden">
          {chips.map((c) => (
            <span key={c.label} className={`chip ${toneCls[c.tone]}`}><span className="font-semibold">{c.label}</span><span className="font-normal text-ink-2">{c.long ?? c.value}</span></span>
          ))}
        </p>
        <p className="pb-2 text-[11px] leading-relaxed text-ink-2">
          Facts (actions, trade, governance) are real data from {real.sources_ok.length} sources, ingested {real.generated_on}, covering {withFacts} of {COUNTRY_COUNT} countries; every block is labelled per panel. Parliament and media carry real records for {withParliament} and {withMedia} countries; stance, tone, translations and narratives are model outputs ({textLabel}). The influence index, concentration measures, say–do gap, flags, event studies, regressions and the finance network are computed from the sourced data (method {real.quant_model?.method_version ?? "–"}); forecasts come from backtested models (naive persistence where nothing beat it) and scenarios are labelled as such; the written analysis is generated from named indicators{interp === "generated+human" ? (briefs && briefs.ai_drafted > 0 ? `, with a brief in the owner's slot shown apart (${briefs.reviewed} of ${briefs.total} reviewed by the project owner; the others AI-drafted from the indicators and marked so)` : ", with the project owner's own text shown apart") : "; no human-written text exists yet"}{real.layers?.statements === "real" ? `; the Politics tab adds ${statements} political statements tagged to a country from the owner's dataset (region-wide records are on the region page), whose stance coding is shown as the dataset's own, not validated` : ""}. Details on the <Link href="/methodology" className="underline">methodology page</Link>.
        </p>
      </details>
    </div>
  );
}
